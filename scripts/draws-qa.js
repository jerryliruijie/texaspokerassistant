async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const active = () => page.locator('.page-draws:not([hidden])');
  const row = id => active().locator(`[data-draw="${id}"]`);
  const open = async id => { if (await row(id).locator('.draw-toggle').getAttribute('aria-expanded') !== 'true') await row(id).locator('.draw-toggle').click(); };
  const stage = async index => { await active().locator('.draw-stage button').nth(index).click(); };
  const rate = async (id, expected) => check(await row(id).locator('.draw-probability').innerText() === expected, `${id}: expected ${expected}`);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(new URL('#draws', page.url()).href); await page.reload();
  await page.getByRole('heading', { name: '听牌', exact: true }).waitFor();
  for (const width of [360, 390, 430]) {
    await page.setViewportSize({ width, height: 844 });
    await stage(0);
    check(await active().locator('.draw-item').count() === 7, 'seven drawing groups');
    await open('flush');
    await row('flush').getByRole('button', { name: '单张手牌 One-card' }).click();
    await row('flush').getByRole('button', { name: '公共牌 2 张红桃' }).click();
    await rate('flush', '0.0%');
    check((await row('flush').locator('.draw-outs-count').innerText()).replace(/\s/g, '') === '连续两张', 'backdoor requires two cards');
    check((await row('flush').locator('.draw-setup').innerText()).includes('21.3%'), 'backdoor setup rate');
    await stage(1); await rate('flush', '4.2%');
    await page.screenshot({ path: `output/playwright/draws-backdoor-${width}.png` });
    await row('flush').getByRole('button', { name: '公共牌 3 张红桃' }).click(); await rate('flush', '35.0%');
    await stage(0); await rate('flush', '19.1%');
    await stage(2);
    await row('flush').getByRole('button', { name: '公共牌 3 张红桃' }).click(); await rate('flush', '19.6%');
    await row('flush').getByRole('button', { name: '公共牌 4 张红桃' }).click(); await rate('flush', '已成花');
    check(await row('flush').locator('.draw-best .playing-card').count() === 5, 'best five flush shown');
    await row('flush').getByRole('button', { name: /持 8♥/ }).click();
    check(await row('flush').locator('.draw-higher-cards .playing-card').count() === 4, 'higher hearts shown');
    check((await row('flush').locator('.draw-opponent').innerText()).includes('更大同花'), 'made flush opponent comparison');
    await page.screenshot({ path: `output/playwright/draws-made-${width}.png` });
    await row('flush').locator('.draw-opponent').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `output/playwright/draws-guide-${width}.png` });
    await row('flush').getByRole('button', { name: '公共牌 2 张红桃' }).click(); await rate('flush', '0.0%');
    await stage(1);
    await row('flush').getByRole('button', { name: '双张手牌 Two-card' }).click();
    await row('flush').getByRole('button', { name: '公共牌 1 张红桃' }).click(); await rate('flush', '4.2%');
    await row('flush').getByRole('button', { name: '公共牌 2 张红桃' }).click(); await rate('flush', '35.0%');
    await open('backdoor');
    await row('backdoor').getByRole('button', { name: '双张手牌 Two-card' }).click();
    await rate('backdoor', '4.2%');
    check(await row('backdoor').locator('.draw-fixed-count').innerText() === '1 张', 'two-card backdoor board has one heart');
    await row('backdoor').getByRole('button', { name: '单张手牌 One-card' }).click();
    await rate('backdoor', '4.2%');
    check(await row('backdoor').locator('.draw-fixed-count').innerText() === '2 张', 'one-card backdoor board has two hearts');
    await open('flush');
    await stage(0);
    await row('flush').locator('[data-risk="5h"]').click();
    check((await row('flush').locator('.draw-risk-explanation').innerText()).includes('公共牌配对'), 'dangerous flush out explanation');
    await open('open-ended');
    await row('open-ended').locator('[data-risk="Ah"]').click();
    check((await row('open-ended').locator('.draw-risk-explanation').innerText()).includes('同花'), 'dangerous straight out explanation');
    await open('double-gutshot'); await rate('double-gutshot', '17.0%');
    await stage(1); await rate('double-gutshot', '31.5%');
    await open('combo');
    check(await row('combo').locator('.draw-out-cards .overlap').count() === 2, 'overlapping outs marked');
    await open('set'); await stage(0);
    check(await row('set').locator('.draw-outs-count').innerText() === '7', 'set flop seven outs');
    await stage(1); await rate('set', '33.4%');
    await stage(2);
    check(await row('set').locator('.draw-outs-count').innerText() === '10', 'set turn ten outs');
    for (const item of await active().locator('.draw-item').all()) {
      if (await item.locator('.draw-toggle').getAttribute('aria-expanded') !== 'true') await item.locator('.draw-toggle').click();
      check(await item.locator('.draw-opponent dl > div').count() === 2, 'two opponent baseline figures');
      check(await item.locator('.draw-actions').isVisible(), 'action clues present');
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'phone has no horizontal overflow');
    }
    await page.locator('.bottom-nav button').first().click(); await page.goBack();
    check(await active().locator('.draw-stage button').last().getAttribute('aria-pressed') === 'true', 'stage preserved');
    check(await row('set').locator('.draw-detail').isVisible(), 'expanded draw preserved');
    await row('set').locator('.draw-toggle').click();
    await stage(0);
    await page.locator('.bottom-nav button').last().click();
    await page.screenshot({ path: `output/playwright/draws-v2-${width}.png` });
    await page.getByRole('button', { name: '规则与数据说明 / Information' }).click();
    check(await page.getByRole('dialog').locator('a').count() === 4, 'all references in information');
    await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'detached' });
  }
  for (const size of [{ width: 360, height: 740 }, { width: 390, height: 750 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(size); await open('flush');
    await row('flush').locator('.draw-actions').scrollIntoViewIfNeeded();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'short/landscape no overflow');
    check(await active().locator('.draw-stage').evaluate(el => el.getBoundingClientRect().top >= -1), 'stage switch stays visible');
  }
  const root = new URL(page.url()); root.hash = '';
  await page.goto(root.href); await page.reload();
  await page.getByRole('heading', { name: '起手牌', exact: true }).waitFor();
  check(errors.length === 0, errors.join('; '));
  return { passed: true, widths: [360, 390, 430], types: 7, singleAndTwoCardFlushCases: 'passed', opponentGuides: 'passed', errors };
}
